# ---------- נרמול שמות לצורך הצלבה ----------
def norm(s):
    if not s:
        return ""
    s = unicodedata.normalize("NFKD", s)
    s = "".join(c for c in s if not unicodedata.combining(c))  # הסרת ניקוד
    s = s.lower()
    s = re.sub(r"[^a-z0-9א-ת]+", " ", s)  # רק אותיות/ספרות עבריות ואנגליות
    return re.sub(r"\s+", " ", s).strip()

def sid(mall, name):
    return hashlib.md5(f"{mall}|{norm(name)}".encode("utf-8")).hexdigest()[:10]

